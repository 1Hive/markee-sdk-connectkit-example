import type { Integration, Severity } from './playground';
import type { MarkeeTheme, Placement } from '@markee_team/sdk';

export function configurationFile(options: {
  integration?: Integration;
  severity?: Severity;
  placement: Placement;
  signTheme: MarkeeTheme;
  modalTheme: MarkeeTheme;
  apiUrl?: string;
}) {
  const shared = { placement: options.placement, moderation: { severity: options.severity ?? 'standard' }, ...(options.apiUrl ? { apiUrl: options.apiUrl } : {}) };
  const sign = JSON.stringify({ ...shared, theme: options.signTheme }, null, 2);
  const modal = JSON.stringify({ ...shared, theme: options.modalTheme }, null, 2);
  const header = `// Generated by the Markee integration playground.
// Install: npm install @markee_team/sdk@latest
// The SDK detects For Sale or For Rent from the selected board.
// If your app has a wallet, pass its SDK WalletAdapter to the sign and modal.
// No API key is required. Match these themes to your app's design.
`;
  if (options.integration === 'vanilla') return `${header}
import { createMarkee, createMarkeeSign } from '@markee_team/sdk';

// Add <div id="markee"></div> to your HTML before running this module.
/** @type {import('@markee_team/sdk').MarkeeSignOptions} */
export const signConfig = ${sign};
/** @type {import('@markee_team/sdk').SDKOptions & { placement: import('@markee_team/sdk').Placement }} */
export const modalConfig = ${modal};
const container = document.getElementById('markee');
if (!container) throw new Error('Missing #markee container');
const { placement, ...modalOptions } = modalConfig;
const markee = createMarkee(modalOptions);
const sign = createMarkeeSign(container, {
  ...signConfig,
  onOpen: () => markee.open({ placement }),
});

// On page teardown, call this to remove listeners and close the modal.
export function cleanup() {
  sign.destroy();
  markee.close();
}
`;
  return `'use client';

${header}
import { useState } from 'react';
import { MarkeeSign, MarkeeModal } from '@markee_team/sdk/react';
import type { MarkeeSignOptions, SDKOptions, WalletAdapter } from '@markee_team/sdk';

export const signConfig = ${sign} satisfies MarkeeSignOptions;
export const modalConfig = ${modal} satisfies SDKOptions & { placement: MarkeeSignOptions['placement'] };

export default function SiteMarkee({ wallet }: { wallet?: WalletAdapter }) {
  const [open, setOpen] = useState(false);
  return <>
    <MarkeeSign {...signConfig} wallet={wallet} onOpen={() => setOpen(true)} />
    <MarkeeModal {...modalConfig} wallet={wallet} open={open} onClose={() => setOpen(false)} />
  </>;
}
`;
}
