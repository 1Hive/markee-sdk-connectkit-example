import type { MarkeeTheme, Placement } from '@markee_team/sdk';

export function configurationFile(options: {
  placement: Placement;
  signTheme: MarkeeTheme;
  modalTheme: MarkeeTheme;
  apiUrl?: string;
  siteUrl?: string;
}) {
  const shared = { placement: options.placement, ...(options.apiUrl ? { apiUrl: options.apiUrl } : {}) };
  return `// Generated by the Markee integration playground.
// Install: npm install @markee_team/sdk@latest
// The SDK detects For Sale or For Rent from the selected board.
import type { MarkeeSignOptions, SDKOptions } from '@markee_team/sdk';

export const signConfig = ${JSON.stringify({ ...shared, theme: options.signTheme }, null, 2)} satisfies MarkeeSignOptions;

export const modalConfig = ${JSON.stringify({ ...shared, ...(options.siteUrl ? { siteUrl: options.siteUrl } : {}), theme: options.modalTheme }, null, 2)} satisfies SDKOptions & { placement: MarkeeSignOptions['placement'] };

// React usage (inside your component):
// import { MarkeeSign, MarkeeModal } from '@markee_team/sdk/react';
// import { signConfig, modalConfig } from './markee.config';
// const [open, setOpen] = useState(false);
// wallet is your app's WalletAdapter; use the connected ConnectKit/wagmi provider.
// <MarkeeSign {...signConfig} onOpen={() => setOpen(true)} />
// <MarkeeModal {...modalConfig} wallet={wallet} open={open} onClose={() => setOpen(false)} />
${options.siteUrl ? '// Set siteUrl to your own deployed page before using this configuration in another app.\n' : ''}`;
}
