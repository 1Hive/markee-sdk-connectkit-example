import type { Integration, Severity } from './playground';
import type { MarkeeTheme, ModerationOptions, PlacementInput } from '@markee_team/sdk';

export function configurationFile(options: {
  integration?: Integration;
  severity?: Severity;
  moderation?: ModerationOptions;
  signTheme: MarkeeTheme;
  modalTheme: MarkeeTheme;
  separateModal?: boolean;
  apiUrl?: string;
} & PlacementInput) {
  const multiBoard = options.multiBoard;
  const common = { moderation: options.moderation ?? { version: 1, severity: options.severity ?? 'standard', rules: {} }, ...(options.apiUrl ? { apiUrl: options.apiUrl } : {}) };
  const shared = multiBoard ? common : { placement: options.placement, ...common };
  const { sign: signOptions, ...baseTheme } = options.signTheme;
  const sharedTheme = JSON.stringify(baseTheme, null, 2);
  const sharedConfig = JSON.stringify(shared, null, 2);
  const sign = `{ ...sharedConfig, theme: ${signOptions ? `{ ...sharedTheme, sign: ${JSON.stringify(signOptions)} }` : 'sharedTheme'} }`;
  const modal = `{ ...sharedConfig, theme: ${options.separateModal === false ? 'sharedTheme' : JSON.stringify(options.modalTheme, null, 2)} }`;
  const header = `// Generated by the Markee integration playground.
// Install: npm install @markee_team/sdk@latest
// ${multiBoard ? 'Pass the current community identity from your app route or project record.' : 'The SDK detects For Sale or For Rent from the selected board.'}
// If your app has a wallet, pass its SDK WalletAdapter to the sign and modal.
// No API key is required. Match these themes to your app's design.
`;
  if (multiBoard) {
    const platformId = JSON.stringify(multiBoard.platformId);
    if (options.integration === 'vanilla') return `${header}
import { createMarkee, createMarkeeSign } from '@markee_team/sdk';

/** @type {import('@markee_team/sdk').MarkeeTheme} */
export const sharedTheme = ${sharedTheme};
/** @type {import('@markee_team/sdk').SDKOptions} */
export const sharedConfig = ${sharedConfig};
/** @type {import('@markee_team/sdk').SDKOptions} */
export const signConfig = ${sign};
/** @type {import('@markee_team/sdk').SDKOptions} */
export const modalConfig = ${modal};

/**
 * Call for each community page using its actual identity chain and ID.
 * @param {HTMLElement} container
 * @param {{ chainId: number, communityId: string, wallet?: import('@markee_team/sdk').WalletAdapter }} page
 */
export function mountMarkee(container, page) {
  const multiBoard = { platformId: ${platformId}, chainId: page.chainId, communityId: page.communityId };
  const markee = createMarkee({ ...modalConfig, wallet: page.wallet });
  const sign = createMarkeeSign(container, {
    ...signConfig, multiBoard, onOpen: () => markee.open({ multiBoard }),
  });
  return () => { sign.destroy(); markee.close(); };
}
`;
    return `'use client';

${header}
import { useState } from 'react';
import { MarkeeSign, MarkeeModal } from '@markee_team/sdk/react';
import type { MarkeeTheme, SDKOptions, WalletAdapter } from '@markee_team/sdk';

export const sharedTheme = ${sharedTheme} satisfies MarkeeTheme;
export const sharedConfig = ${sharedConfig} satisfies SDKOptions;
export const signConfig = ${sign} satisfies SDKOptions;
export const modalConfig = ${modal} satisfies SDKOptions;

export default function SiteMarkee({ chainId, communityId, wallet }: { chainId: number; communityId: string; wallet?: WalletAdapter }) {
  const [open, setOpen] = useState(false);
  const multiBoard = { platformId: ${platformId}, chainId, communityId };
  return <>
    <MarkeeSign {...signConfig} multiBoard={multiBoard} onOpen={() => setOpen(true)} />
    <MarkeeModal {...modalConfig} multiBoard={multiBoard} wallet={wallet} open={open} onClose={() => setOpen(false)} />
  </>;
}
`;
  }
  if (options.integration === 'vanilla') return `${header}
import { createMarkee, createMarkeeSign } from '@markee_team/sdk';

// Add <div id="markee"></div> to your HTML before running this module.
/** @type {import('@markee_team/sdk').MarkeeTheme} */
export const sharedTheme = ${sharedTheme};
/** @type {import('@markee_team/sdk').SDKOptions & { placement: import('@markee_team/sdk').Placement }} */
export const sharedConfig = ${sharedConfig};
/** @type {import('@markee_team/sdk').MarkeeSignOptions} */
export const signConfig = ${sign};
/** @type {import('@markee_team/sdk').SDKOptions & { placement: import('@markee_team/sdk').Placement }} */
export const modalConfig = ${modal};
const container = document.getElementById('markee');
if (!container) throw new Error('Missing #markee container');
const { placement, ...modalOptions } = modalConfig;
const markee = createMarkee(modalOptions);
const sign = createMarkeeSign(container, {
  ...signConfig,
  onOpen: () => markee.open({ placement }),
});

// On page teardown, call this to remove listeners and close the modal.
export function cleanup() {
  sign.destroy();
  markee.close();
}
`;
  return `'use client';

${header}
import { useState } from 'react';
import { MarkeeSign, MarkeeModal } from '@markee_team/sdk/react';
import type { MarkeeTheme, MarkeeSignOptions, SDKOptions, WalletAdapter } from '@markee_team/sdk';

export const sharedTheme = ${sharedTheme} satisfies MarkeeTheme;
export const sharedConfig = ${sharedConfig} satisfies SDKOptions & { placement: MarkeeSignOptions['placement'] };

export const signConfig = ${sign} satisfies MarkeeSignOptions;
export const modalConfig = ${modal} satisfies SDKOptions & { placement: MarkeeSignOptions['placement'] };

export default function SiteMarkee({ wallet }: { wallet?: WalletAdapter }) {
  const [open, setOpen] = useState(false);
  return <>
    <MarkeeSign {...signConfig} wallet={wallet} onOpen={() => setOpen(true)} />
    <MarkeeModal {...modalConfig} wallet={wallet} open={open} onClose={() => setOpen(false)} />
  </>;
}
`;
}
